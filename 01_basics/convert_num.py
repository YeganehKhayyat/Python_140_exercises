# Write a Python Program to Convert Decimal to Binary, Octal and Hexadecimal

num = int(input("\nEnter a number to convert to binary, octal and Hexadecimal : "))

print(f"\nbinary form of {num} is : {bin(num)}")
print(f"\noctal form of {num} is : {oct(num)}")
print(f"\nHexadecimal form of {num} is : {hex(num)}")
